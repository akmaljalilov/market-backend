-- ============================================================
-- PRODUCTS
-- ============================================================

CREATE TABLE products (
                          id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR NOT NULL,
                          category_id INT NOT NULL,
                          created TIMESTAMP NOT NULL DEFAULT NOW(),
                          updated TIMESTAMP NOT NULL DEFAULT NOW(),

                          CONSTRAINT fk_products_category
                              FOREIGN KEY (category_id)
                                  REFERENCES categories(id)
);


-- ============================================================
-- PRODUCTS BALANCE
-- ============================================================

CREATE TABLE products_balance (
                                  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  product_id INT NOT NULL UNIQUE,
                                  quantity NUMERIC(12, 3) NOT NULL DEFAULT 0,
                                  amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
                                  created TIMESTAMP NOT NULL DEFAULT NOW(),
                                  updated TIMESTAMP NOT NULL DEFAULT NOW(),

                                  CONSTRAINT fk_products_balance_product
                                      FOREIGN KEY (product_id)
                                          REFERENCES products(id),

                                  CONSTRAINT chk_products_balance_quantity
                                      CHECK (quantity >= 0),

                                  CONSTRAINT chk_products_balance_amount
                                      CHECK (amount >= 0)
);


-- ============================================================
-- STOCK MOVEMENTS
-- ============================================================

CREATE TABLE stock_movements (
                                 id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 product_id INT NOT NULL,
                                 movement_type stock_action NOT NULL,
                                 quantity NUMERIC(12, 3) NOT NULL,
                                 unit_price NUMERIC(12, 2) NOT NULL,

                                 total_amount NUMERIC(12, 2)
                                     GENERATED ALWAYS AS (quantity * unit_price) STORED,

                                 created TIMESTAMP NOT NULL DEFAULT NOW(),

                                 CONSTRAINT fk_stock_movements_product
                                     FOREIGN KEY (product_id)
                                         REFERENCES products(id),

                                 CONSTRAINT chk_stock_movements_quantity
                                     CHECK (quantity > 0),

                                 CONSTRAINT chk_stock_movements_price
                                     CHECK (unit_price >= 0)
);


-- ============================================================
-- SALES
-- ============================================================

CREATE TABLE sales (
                       id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       cashier_id UUID NOT NULL,
                       client_id UUID,
                       total_amount NUMERIC(12, 2) NOT NULL,
                       status sale_status NOT NULL DEFAULT 'pending',
                       created TIMESTAMP NOT NULL DEFAULT NOW(),

