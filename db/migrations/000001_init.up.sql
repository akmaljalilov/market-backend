-- ============================================================
-- PURCHASE / RESTOCK FUNCTION
-- ============================================================

CREATE OR REPLACE FUNCTION inp_product()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

INSERT INTO stock_movements (
    product_id,
    movement_type,
    quantity,
    unit_price
)
VALUES (
           NEW.product_id,
           'restock',
           NEW.quantity,
           NEW.price
       );

INSERT INTO products_balance (
    product_id,
    quantity,
    amount
)
VALUES (
           NEW.product_id,
           NEW.quantity,
           NEW.price
       )
    ON CONFLICT (product_id)
    DO UPDATE SET
    quantity = products_balance.quantity + EXCLUDED.quantity,
               amount = products_balance.amount + EXCLUDED.amount,
               updated = CURRENT_TIMESTAMP;

RETURN NEW;
END;
$$;


-- ============================================================
-- SALE / STOCK OUT FUNCTION
-- ============================================================

CREATE OR REPLACE FUNCTION out_product()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
current_quantity NUMERIC(12, 3);
    current_amount NUMERIC(12, 2);
    cost_per_unit NUMERIC(12, 6);
    stock_cost NUMERIC(12, 2);
BEGIN

SELECT
    quantity,
    amount
INTO
    current_quantity,
    current_amount
FROM products_balance
WHERE product_id = NEW.product_id
    FOR UPDATE;

IF current_quantity IS NULL THEN
        RAISE EXCEPTION
            'Product % has no stock balance',
            NEW.product_id;
END IF;

    IF current_quantity < NEW.quantity THEN
        RAISE EXCEPTION
            'Insufficient stock for product %. Current quantity: %, requested: %',
            NEW.product_id,
            current_quantity,
            NEW.quantity;
END IF;

    IF current_quantity > 0 THEN
        cost_per_unit := current_amount / current_quantity;
ELSE
        cost_per_unit := 0;
END IF;

    stock_cost := ROUND(
        NEW.quantity * cost_per_unit,
        2
    );

INSERT INTO stock_movements (
    product_id,
    movement_type,
    quantity,
    unit_price
)
VALUES (
           NEW.product_id,
           'sale',
           NEW.quantity,
           NEW.price
       );

UPDATE products_balance
SET
    quantity = quantity - NEW.quantity,
    amount = GREATEST(amount - stock_cost, 0),
    updated = CURRENT_TIMESTAMP
WHERE product_id = NEW.product_id;

RETURN NEW;
END;
$$;


-- ============================================================
-- PURCHASE EXPENSE FUNCTION
-- ============================================================

CREATE OR REPLACE FUNCTION expenses_product()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
product_id_value INT;
BEGIN

SELECT product_id
INTO product_id_value
FROM purchase_items
WHERE id = NEW.purchase_item_id;

IF product_id_value IS NULL THEN
        RAISE EXCEPTION
            'Purchase item % does not exist',
            NEW.purchase_item_id;
END IF;

INSERT INTO products_balance (
    product_id,
    quantity,
    amount
)
VALUES (
           product_id_value,
           0,
           NEW.amount
       )
    ON CONFLICT (product_id)
    DO UPDATE SET
    amount = products_balance.amount + EXCLUDED.amount,
               updated = CURRENT_TIMESTAMP;

RETURN NEW;
END;
$$;


-- ============================================================
-- TRIGGERS
-- ============================================================

CREATE TRIGGER trg_purchase_item_stock_in
    AFTER INSERT ON purchase_items
    FOR EACH ROW
    EXECUTE FUNCTION inp_product();


CREATE TRIGGER trg_sale_item_stock_out
    AFTER INSERT ON sale_items
    FOR EACH ROW
    EXECUTE FUNCTION out_product();


CREATE TRIGGER trg_purchase_expense_balance
    AFTER INSERT ON purchase_expenses
    FOR EACH ROW
    EXECUTE FUNCTION expenses_product();


